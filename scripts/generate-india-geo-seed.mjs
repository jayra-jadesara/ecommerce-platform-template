/**
 * Generates SQL seed inserts for india_states / india_cities from JSON.
 * Run: node scripts/generate-india-geo-seed.mjs
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const raw = JSON.parse(
  readFileSync(join(root, "src/features/geo/india-states-cities.json"), "utf8"),
);

function esc(value) {
  return String(value)
    .replace(/&amp;/g, "&")
    .replace(/\s+/g, " ")
    .trim()
    .replace(/'/g, "''");
}

const states = Array.isArray(raw.states) ? raw.states : [];
const lines = [];
lines.push("-- Auto-generated by scripts/generate-india-geo-seed.mjs — do not edit by hand.");
lines.push("truncate table public.india_cities restart identity cascade;");
lines.push("truncate table public.india_states restart identity cascade;");
lines.push("");

states.forEach((entry, index) => {
  const stateName = esc(entry.state);
  const sort = index + 1;
  lines.push(
    `insert into public.india_states (name, sort_order) values ('${stateName}', ${sort});`,
  );
  const districts = Array.isArray(entry.districts) ? entry.districts : [];
  for (const city of districts) {
    const cityName = esc(city);
    if (!cityName) continue;
    lines.push(
      `insert into public.india_cities (state_id, name) select id, '${cityName}' from public.india_states where name = '${stateName}';`,
    );
  }
  lines.push("");
});

const out = join(root, "supabase/seed/india_geo_data.sql");
writeFileSync(out, lines.join("\n"), "utf8");
console.log(`Wrote ${out} (${states.length} states)`);
