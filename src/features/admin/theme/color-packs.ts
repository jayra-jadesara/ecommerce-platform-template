export const THEME_COLOR_PACK_CATEGORIES: ThemeColorPackCategory[] = [
  "Nature",
  "Warm",
  "Modern",
  "Luxury",
  "Soft",
  "Bold",
  "Neutral",
  "Dark",
];

export function packsByCategory(): Array<{
  category: ThemeColorPackCategory;
  packs: ThemeColorPack[];
}> {
  return THEME_COLOR_PACK_CATEGORIES.map((category) => ({
    category,
    packs: THEME_COLOR_PACKS.filter((packItem) => packItem.category === category),
  })).filter((group) => group.packs.length > 0);
}

export function findMatchingThemePackId(
  light: ColorTokens,
  dark: ColorTokens,
): string | null {
  for (const packItem of THEME_COLOR_PACKS) {
    if (
      packItem.light.primary === light.primary &&
      packItem.light.background === light.background &&
      packItem.dark.primary === dark.primary &&
      packItem.dark.background === dark.background
    ) {
      return packItem.id;
    }
  }
  return null;
}
