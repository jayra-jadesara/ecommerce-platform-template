import type { ColorTokens } from "@/types";

function withChrome(
  base: Omit<
    ColorTokens,
    | "headerBackground"
    | "headerForeground"
    | "footerBackground"
    | "footerForeground"
    | "buttonBackground"
    | "buttonForeground"
  >,
  buttonForeground: string,
): ColorTokens {
  return {
    ...base,
    headerBackground: base.surface,
    headerForeground: base.foreground,
    footerBackground: base.surface,
    footerForeground: base.muted,
    buttonBackground: base.primary,
    buttonForeground,
  };
}

export type ThemeColorPackCategory =
  | "Nature"
  | "Warm"
  | "Modern"
  | "Luxury"
  | "Soft"
  | "Bold"
  | "Neutral"
  | "Dark";

export type ThemeColorPack = {
  id: string;
  name: string;
  description: string;
  category: ThemeColorPackCategory;
  /** Swatches: primary, secondary, accent, background */
  preview: [string, string, string, string];
  light: ColorTokens;
  dark: ColorTokens;
};

function pack(
  id: string,
  name: string,
  description: string,
  category: ThemeColorPackCategory,
  lightBase: Parameters<typeof withChrome>[0],
  lightBtnFg: string,
  darkBase: Parameters<typeof withChrome>[0],
  darkBtnFg: string,
): ThemeColorPack {
  const light = withChrome(lightBase, lightBtnFg);
  const dark = withChrome(darkBase, darkBtnFg);
  return {
    id,
    name,
    description,
    category,
    preview: [light.primary, light.secondary, light.accent, light.background],
    light,
    dark,
  };
}

